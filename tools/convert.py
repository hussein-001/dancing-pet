"""Turn the GIF stickers into the mod's frame data.

usage: python tools/convert.py <gif folder> plugin/hooks/stickers.ts

Each pose is written as readable source: one pixel row per line, a palette
key per pixel ('.' is transparent), split into files the directory can read
whole (under 200 KB each). stickers.ts imports them all.
"""
import glob, json, os, re, sys
from collections import Counter
from PIL import Image, ImageSequence
SRC, OUT = sys.argv[1], sys.argv[2]
ART_ROWS = 52  # grid rows above the word label
def grid(frame):
    f = frame.convert('RGBA')
    return [[f.getpixel((c*8+4, r*8+4)) for c in range(64)] for r in range(ART_ROWS)]
def half(g):
    out = []
    for r in range(0, ART_ROWS, 2):
        row = []
        for c in range(0, 64, 2):
            px = [g[r+dr][c+dc] for dr in (0,1) for dc in (0,1)]
            cs = [p[:3] for p in px if p[3] > 128 and p[:3] != (255,255,255)]
            row.append(Counter(cs).most_common(1)[0][0] if cs else None)
        out.append(row)
    return out
stickers = []
for path in sorted(glob.glob(os.path.join(SRC, '*.gif'))):
    word = re.sub(r'^\d+-', '', os.path.basename(path)[:-4])
    im = Image.open(path)
    frames = [half(grid(f)) for f in ImageSequence.Iterator(im)]
    stickers.append((word, frames, im.info.get('duration', 90)))
# shared bounding box so every sticker has the same raster size
rows = [r for _, fs, _ in stickers for f in fs for r, row in enumerate(f) if any(row)]
cols = [c for _, fs, _ in stickers for f in fs for row in f for c, p in enumerate(row) if p]
r0, r1, c0, c1 = min(rows), max(rows), min(cols), max(cols)
H = r1 - r0 + 1; H += H % 2; W = c1 - c0 + 1
KEYS = '.ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
data = {}
for word, frames, dur in stickers:
    pal = []
    enc = []
    for f in frames:
        s = []
        for r in range(r0, r0 + H):
            for c in range(c0, c1 + 1):
                p = f[r][c] if r < len(f) else None
                if p is None: s.append('.'); continue
                h = (p[0] << 16) | (p[1] << 8) | p[2]
                if h not in pal:
                    if len(pal) < len(KEYS) - 1: pal.append(h)
                    else: h = min(pal, key=lambda q: sum((((q >> k) & 255) - ((h >> k) & 255)) ** 2 for k in (0, 8, 16)))
                s.append(KEYS[pal.index(h) + 1])
        enc.append(''.join(s))
    data[word] = {'p': pal, 'f': enc, 'd': dur}
OUTDIR = os.path.join(os.path.dirname(OUT), 'frames')
os.makedirs(OUTDIR, exist_ok=True)
for old in glob.glob(os.path.join(OUTDIR, '*.ts')):
    os.remove(old)
for old in glob.glob(os.path.join(os.path.dirname(OUT), 'stickers-*.ts')):
    os.remove(old)
HEADER = ('// Generated by tools/convert.py from the GIF stickers. Do not edit by hand.\n'
          "// Each frame is one string per pixel row; a letter or digit is a palette entry, '.' is transparent.\n")
LIMIT = 200 * 1024


def entry(word, sticker):
    lines = [f'  {json.dumps(word)}: {{', f"    d: {sticker['d']},", '    p: [']
    pal = sticker['p']
    for i in range(0, len(pal), 8):
        lines.append('      ' + ', '.join('0x%06x' % c for c in pal[i:i + 8]) + ',')
    lines.append('    ],')
    lines.append('    f: [')
    for frame in sticker['f']:
        lines.append('      [')
        for r in range(H):
            lines.append("        '" + frame[r * W:(r + 1) * W] + "',")
        lines.append('      ],')
    lines.append('    ],')
    lines.append('  },')
    return '\n'.join(lines) + '\n'


parts, current, size = [], [], 0
for word, sticker in data.items():
    text = entry(word, sticker)
    if current and size + len(text) > LIMIT:
        parts.append(current)
        current, size = [], 0
    current.append(text)
    size += len(text)
parts.append(current)
names = []
for n, part in enumerate(parts, start=1):
    name = 'part-%02d' % n
    names.append(name)
    path = os.path.join(OUTDIR, name + '.ts')
    with open(path, 'w') as f:
        f.write(HEADER + "import type { Sticker } from '../stickers'\n\n")
        f.write('export const PART: Record<string, Sticker> = {\n' + ''.join(part) + '}\n')
src = (HEADER
       + ''.join(f"import {{ PART as P{n} }} from './frames/{nm}'\n" for n, nm in enumerate(names))
       + f'\nexport const WIDTH = {W}\nexport const HEIGHT = {H}\n'
       + "export const KEYS = '" + KEYS + "'\n\n"
       + '// d: milliseconds per frame; p: palette as 0xRRGGBB; f: frames, each HEIGHT rows of WIDTH keys\n'
       + 'export type Sticker = { d: number; p: number[]; f: string[][] }\n\n'
       + 'export const STICKERS: Record<string, Sticker> = {\n'
       + ''.join(f'  ...P{n},\n' for n in range(len(names))) + '}\n')
open(OUT, 'w').write(src)
print(len(data), 'stickers in', len(names), 'files', W, 'x', H)
